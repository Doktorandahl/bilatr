# Equivalence of the replication pipeline ported to bilatr 1.0.0 (1.0.0e)
# with the 0.12.0c pipeline, for both production models.
#
# New side: runscripts/bilatr_replication/{config.R,R/functions.R} as ported in
# 1.0.0e, sourced unchanged in a callr subprocess with the bilatr 1.0.0
# tarball installed in `lib_new`. Old side: the same two files as they were
# before 1.0.0e (from the runscripts backup, extracted to `old_repl_dir`),
# with bilatr 0.12.0 (commit 8dd934f) installed in `lib_old`. Both call
# build_stan_data() in FULL mode with output_root in a temporary directory.
#
# Checks: every list field identical(); T, C and the 0/1 flags compared
# with as.integer() when their storage type differs (1.0.0 stores them as
# integers); the list names; every attribute identical(); and Y/is_obs md5
# equal to the hashes recorded against 0.10.2 in equivalence_0.12.0a.md.
# Writes data-raw/equivalence/equivalence_1.0.0e.md.
#
#   Rscript data-raw/equivalence/equivalence_1.0.0e.R <lib_new> <lib_old> <old_repl_dir>
# Pure R, no Stan.

args <- commandArgs(trailingOnly = TRUE)
lib_new <- normalizePath(args[1], mustWork = TRUE)
lib_old <- normalizePath(args[2], mustWork = TRUE)
old_repl_dir <- normalizePath(args[3], mustWork = TRUE)
new_repl_dir <- normalizePath("runscripts/bilatr_replication", mustWork = TRUE)
report_path <- "data-raw/equivalence/equivalence_1.0.0e.md"
models <- c(directed = "bilatr_16cat_directed", undirected = "bilatr_16cat_undirected")
expected_md5 <- list(
  directed = c(Y = "4ed0ffdf392325ea2334744f9ae49f8a", is_obs = "f8a7113a838ce67b0c00fcee99aa216f"),
  undirected = c(Y = "0950349b6be363670e63fdd93291ed4d", is_obs = "1ed92de73b3c72858e41b2d5a9bbd716")
)

side <- function(repl_dir, out_root, models) {
  Sys.unsetenv("BILATR_TEST_MODE")
  setwd(repl_dir)
  source("config.R", local = FALSE)
  stopifnot(!test_mode)
  output_root <<- out_root
  overwrite <<- TRUE
  source("R/functions.R", local = FALSE)
  res <- list(version = as.character(utils::packageVersion("bilatr")),
              lib = dirname(find.package("bilatr")), stan_data = list(), seconds = list())
  for (s in names(models)) {
    t0 <- proc.time()[["elapsed"]]
    res$stan_data[[s]] <- suppressMessages(build_stan_data(models[[s]]))
    res$seconds[[s]] <- proc.time()[["elapsed"]] - t0
  }
  res
}
run_side <- function(repl_dir, lib) {
  callr::r(side, args = list(repl_dir = repl_dir, out_root = tempfile("repl_out_"), models = models),
           libpath = c(lib, .libPaths()), show = TRUE)
}
message("new side (bilatr 1.0.0) ...")
new <- run_side(new_repl_dir, lib_new)
message("old side (bilatr 0.12.0c) ...")
old <- run_side(old_repl_dir, lib_old)
stopifnot(new$version == "1.0.0", old$version == "0.12.0")

int_ok_fields <- c("T", "C", "compute_log_lik", "prior_only", "compute_theta_filtered")
compare_one <- function(o, n) {
  fields <- union(names(o), names(n))
  how <- vapply(fields, function(f) {
    if (identical(o[[f]], n[[f]])) return("identical")
    if (f %in% int_ok_fields && identical(as.integer(o[[f]]), as.integer(n[[f]]))) {
      return(sprintf("equal as integer (%s -> %s)", typeof(o[[f]]), typeof(n[[f]])))
    }
    "**DIFFERENT**"
  }, "")
  attrs <- setdiff(union(names(attributes(o)), names(attributes(n))), "names")
  attr_how <- vapply(attrs, function(a) {
    if (identical(attr(o, a), attr(n, a))) "identical" else "**DIFFERENT**"
  }, "")
  list(fields = how, attrs = attr_how, names_ok = identical(names(o), names(n)))
}
res <- lapply(names(models), function(s) compare_one(old$stan_data[[s]], new$stan_data[[s]]))
names(res) <- names(models)
md5 <- lapply(names(models), function(s) {
  sd <- new$stan_data[[s]]
  c(Y = digest::digest(sd$Y, algo = "md5"), is_obs = digest::digest(sd$is_obs, algo = "md5"))
})
names(md5) <- names(models)
md5_ok <- vapply(names(models), function(s) identical(md5[[s]], expected_md5[[s]]), logical(1))
all_ok <- all(vapply(res, function(r) r$names_ok && !any(grepl("DIFFERENT", c(r$fields, r$attrs))), logical(1))) &&
  all(md5_ok)

lines <- c(
  "# Equivalence of the replication pipeline ported to 1.0.0 with 0.12.0c",
  "",
  sprintf("Generated by `data-raw/equivalence/equivalence_1.0.0e.R` on %s.", format(Sys.time(), "%Y-%m-%d %H:%M %Z")),
  "",
  sprintf("- new: `build_stan_data()` from the 1.0.0e `runscripts/bilatr_replication/`, bilatr %s installed from the built tarball (`%s`)", new$version, new$lib),
  sprintf("- old: the same files before 1.0.0e (runscripts backup), bilatr %s from commit `8dd934f` (`%s`)", old$version, old$lib),
  "- both: `config.R` unchanged, full mode (ModifiedRootCode, reference \"5\", yearly 1991-2025, `min_n_events = 1`, chunk size 1200, `compute_theta_filtered = 1`), output in a temporary directory",
  "",
  sprintf("**Overall: %s**", if (all_ok) "identical for both models (storage-type changes only where allowed)" else "NOT EQUIVALENT"),
  "",
  "| model | D | T | A | n_countries | seconds new / old |", "| --- | --- | --- | --- | --- | --- |"
)
for (s in names(models)) {
  sd <- new$stan_data[[s]]
  lines <- c(lines, sprintf("| %s | %d | %d | %d | %d | %.1f / %.1f |", models[[s]], sd$D, sd$T, sd$A,
                            sd$n_countries, new$seconds[[s]], old$seconds[[s]]))
}
lines <- c(lines, "", "## Fields", "", "| field | directed | undirected |", "| --- | --- | --- |")
for (f in names(res$directed$fields)) {
  lines <- c(lines, sprintf("| `%s` | %s | %s |", f, res$directed$fields[[f]], res$undirected$fields[[f]]))
}
lines <- c(lines, sprintf("| (list names, in order) | %s | %s |", res$directed$names_ok, res$undirected$names_ok),
           "", "## Attributes", "", "| attribute | directed | undirected |", "| --- | --- | --- |")
for (a in names(res$directed$attrs)) {
  lines <- c(lines, sprintf("| `%s` | %s | %s |", a, res$directed$attrs[[a]], res$undirected$attrs[[a]]))
}
lines <- c(lines, "", "## md5 vs 0.10.2 (`equivalence_0.12.0a.md`)", "",
           "| model | `Y` | `is_obs` | match |", "| --- | --- | --- | --- |")
for (s in names(models)) {
  lines <- c(lines, sprintf("| %s | `%s` | `%s` | %s |", s, md5[[s]][["Y"]], md5[[s]][["is_obs"]], md5_ok[[s]]))
}
writeLines(lines, report_path)
message("wrote ", report_path, if (all_ok) " (equivalent)" else " (NOT EQUIVALENT)")
